"""LangGraph state machine assembly, checkpointer compilation, Mermaid export, and runner."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any
from uuid import UUID, uuid4

from langgraph.checkpoint.base import BaseCheckpointSaver
from langgraph.checkpoint.memory import MemorySaver
from langgraph.graph import END, START, StateGraph
from sqlalchemy.orm import Session

from ledgerpilot.ai.adapter import GroqModelAdapter
from ledgerpilot.audit.edges import (
    route_after_aggregate,
    route_after_load,
    route_after_polish,
    route_after_validate,
)
from ledgerpilot.audit.nodes import (
    AuditRuntimeDeps,
    aggregate_findings,
    detect_anomalies,
    empty_report,
    fallback_report,
    flag_critical_findings,
    handle_invalid_request,
    make_load_data_node,
    make_persist_and_return_node,
    make_polish_report_node,
    make_validate_request_node,
    reconcile,
    retrieve_context,
    run_rules,
)
from ledgerpilot.audit.state import AuditMode, AuditState, TriggerSource
from ledgerpilot.config import Settings, get_settings

SHARED_AUDIT_CHECKPOINTER = MemorySaver()


def build_audit_graph(
    deps: AuditRuntimeDeps,
    *,
    checkpointer: BaseCheckpointSaver[Any] | None = None,
) -> Any:
    """Build and compile the LangGraph financial audit workflow with checkpointing."""
    workflow = StateGraph(AuditState)

    workflow.add_node("validate_request", make_validate_request_node(deps))
    workflow.add_node("handle_invalid_request", handle_invalid_request)
    workflow.add_node("load_data", make_load_data_node(deps))
    workflow.add_node("empty_report", empty_report)
    workflow.add_node("retrieve_context", retrieve_context)
    workflow.add_node("run_rules", run_rules)
    workflow.add_node("reconcile", reconcile)
    workflow.add_node("detect_anomalies", detect_anomalies)
    workflow.add_node("aggregate_findings", aggregate_findings)
    workflow.add_node("flag_critical_findings", flag_critical_findings)
    workflow.add_node("polish_report", make_polish_report_node(deps))
    workflow.add_node("fallback_report", fallback_report)
    workflow.add_node("persist_and_return", make_persist_and_return_node(deps))

    workflow.add_edge(START, "validate_request")
    workflow.add_conditional_edges(
        "validate_request",
        route_after_validate,
        {
            "load_data": "load_data",
            "handle_invalid_request": "handle_invalid_request",
        },
    )
    workflow.add_edge("handle_invalid_request", END)

    workflow.add_conditional_edges(
        "load_data",
        route_after_load,
        [
            "empty_report",
            "retrieve_context",
            "run_rules",
            "reconcile",
            "detect_anomalies",
        ],
    )
    workflow.add_edge("empty_report", "persist_and_return")

    # Parallel fan-in: all four analysis branches converge on aggregate_findings
    workflow.add_edge("retrieve_context", "aggregate_findings")
    workflow.add_edge("run_rules", "aggregate_findings")
    workflow.add_edge("reconcile", "aggregate_findings")
    workflow.add_edge("detect_anomalies", "aggregate_findings")

    workflow.add_conditional_edges(
        "aggregate_findings",
        route_after_aggregate,
        {
            "flag_critical_findings": "flag_critical_findings",
            "polish_report": "polish_report",
        },
    )
    workflow.add_edge("flag_critical_findings", "polish_report")

    workflow.add_conditional_edges(
        "polish_report",
        route_after_polish,
        {
            "fallback_report": "fallback_report",
            "persist_and_return": "persist_and_return",
        },
    )
    workflow.add_edge("fallback_report", "persist_and_return")
    workflow.add_edge("persist_and_return", END)

    saver = checkpointer if checkpointer is not None else SHARED_AUDIT_CHECKPOINTER
    return workflow.compile(checkpointer=saver)


def get_audit_graph_mermaid() -> str:
    """Return the exact Mermaid diagram generated by LangGraph's draw_mermaid()."""

    class _DummySession:
        pass

    dummy_deps = AuditRuntimeDeps(
        db=_DummySession(),  # type: ignore[arg-type]
        settings=get_settings(),
        persist=False,
    )
    compiled = build_audit_graph(dummy_deps, checkpointer=MemorySaver())
    return str(compiled.get_graph().draw_mermaid())


def execute_financial_audit(
    db: Session,
    *,
    business_id: UUID,
    actor_id: UUID,
    audit_type: AuditMode,
    trigger_source: TriggerSource = "manual",
    request_params: dict[str, Any] | None = None,
    scope_filters: dict[str, Any] | None = None,
    settings: Settings | None = None,
    adapter: GroqModelAdapter | None = None,
    checkpointer: BaseCheckpointSaver[Any] | None = None,
    run_id: UUID | None = None,
    job_id: UUID | None = None,
    persist: bool = True,
) -> dict[str, Any]:
    """Execute a complete LangGraph financial audit and return machine + polished output."""
    cfg = settings or get_settings()
    resolved_run_id = str(run_id or uuid4())
    thread_id = f"audit-{business_id}-{resolved_run_id}"

    deps = AuditRuntimeDeps(
        db=db,
        settings=cfg,
        adapter=adapter,
        persist=persist,
    )
    compiled = build_audit_graph(deps, checkpointer=checkpointer)

    initial_state: AuditState = {
        "run_id": resolved_run_id,
        "thread_id": thread_id,
        "business_id": str(business_id),
        "actor_id": str(actor_id),
        "audit_type": audit_type,
        "trigger_source": trigger_source,
        "request_params": dict(request_params or {}),
        "scope_filters": dict(scope_filters or {}),
        "rule_results": [],
        "candidate_findings": [],
        "errors": [],
        "node_trace": [],
        "metadata": {
            "started_at": datetime.now(UTC).isoformat(),
            "job_id": str(job_id) if job_id else None,
        },
    }

    final_state: dict[str, Any] = compiled.invoke(
        initial_state,
        config={"configurable": {"thread_id": thread_id}},
    )

    valid = bool(final_state.get("validation_valid", False))
    has_data = bool(final_state.get("has_data", False))
    status = "failed" if not valid else "completed_empty" if not has_data else "completed"

    return {
        "id": resolved_run_id,
        "business_id": str(business_id),
        "audit_type": audit_type,
        "trigger_source": trigger_source,
        "status": status,
        "thread_id": thread_id,
        "job_id": str(job_id) if job_id else None,
        "period": final_state.get("period") or {},
        "scope_filters": final_state.get("scope_filters") or {},
        "loaded_data_summary": final_state.get("loaded_data_summary") or {},
        "severity_summary": final_state.get("severity_summary") or {},
        "critical_flagged": bool(final_state.get("critical_flagged", False)),
        "findings": final_state.get("findings") or [],
        "retrieved_context": final_state.get("retrieved_context") or [],
        "raw_report": final_state.get("raw_report") or {},
        "polished_report": final_state.get("polished_report") or {},
        "errors": final_state.get("errors") or [],
        "metadata": final_state.get("metadata") or {},
    }
